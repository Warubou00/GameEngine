#pragma once
#ifndef DIRECT_INPUT_H_
#define DIRECT_INPUT_H_

/******************************************************************
* Include Headers
******************************************************************/
#ifndef DIRECTINPUT_VERSION
#define DIRECTINPUT_VERSION 0x0800		// 警告対処
#endif
#ifndef NOMINMAX
#define NOMINMAX
#endif
#include <windows.h>
#include <dinput.h>

/******************************************************************
* Link Library
******************************************************************/
#pragma comment (lib, "dxguid.lib")
#pragma comment (lib, "dinput8.lib")

/******************************************************************
* Macro Definitions
******************************************************************/


/******************************************************************
* Enumeration Definitions
******************************************************************/


/******************************************************************
* Structure Declarations
******************************************************************/



namespace ko
{


	/***********************************************************************************
	 * @brief   DirectInputのキーコンフィグクラス
	 ************************************************************************************/
    class DirectInput
    {

        /******************************************************************
        * Internal Enumeration Declarations
        ******************************************************************/


        /******************************************************************
        * Internal Structure Declarations
        ******************************************************************/


    private:          /*---コンストラクタ---*/
		DirectInput() = default;
		~DirectInput() {}		// COM の解放は Release で (DLL を外す時 = DllMain の中で COM を触らない)


    public:          /*---クラスメソッド---*/


		/***********************************************************************************
		 * @brief シングルトンのインスタンス取得
		 * @details シングルトンのインスタンス取得
		 *
		 * @return DirectInput* 自身のインスタンスを返却
		 ************************************************************************************/
		static DirectInput* getInstance();


		/***********************************************************************************
		 * @brief 初期化
		 * @details 初期化
		 *
		 * @param[HINSTANCE] hInstance ウインドウインスタンスハンドル
		 * @return HRESULT 成功の有無
		 ************************************************************************************/
		HRESULT Init(HINSTANCE hInstance);


		/***********************************************************************************
		 * @brief 更新
		 * @details 更新
		 *
		 * @return 無し
		 ************************************************************************************/
		void Update(void);


		/***********************************************************************************
		 * @brief 解放
		 * @details 解放
		 *
		 * @return 無し
		 ************************************************************************************/
		void Release(void) { if (_iDevice) { _iDevice->Release(); _iDevice = nullptr; } }

    public:          /*---アクセッサー関数群---*/

		/***********************************************************************************
		 * @brief IDirectInput8*の取得
		 * @details 取得
		 *
		 * @return IDirectInput8* ダイレクトインプットのデバイス
		 ************************************************************************************/
		IDirectInput8* GetDevice(void)const { return _iDevice; }

    private:         /*---メンバ変数---*/
		IDirectInput8* _iDevice = nullptr;			// デバイス

    };

}


#endif // DIRECT_INPUT_H_

